  assert_contains "check names the drifted rule" "$rule_output" "Cursor adapter drift for hephaestus.mdc"
fi

begin_test "Cursor adapter check detects stale adapters after source deletion"

FIXTURE2=$(mktemp -d "${TMPDIR:-/tmp}/heph-cursor-XXXXXX")
trap 'rm -rf "$FIXTURE" "$FIXTURE_RULE" "$FIXTURE2"' EXIT

copy_fixture "$FIXTURE2"

rm "$FIXTURE2/.ai/workflows/research.md"
rm "$FIXTURE2/.claude/agents/tester.md"

if stale_output=$(bash "$FIXTURE2/scripts/sync-cursor-adapters.sh" --check 2>&1); then
  fail "Cursor check should detect orphaned adapters" "exited 0, output: $stale_output"
else
  assert_contains "check names stale command adapter" "$stale_output" ".cursor/commands/research.md"
  assert_contains "check names stale subagent adapter" "$stale_output" ".cursor/agents/tester.md"
fi

sync_output=$(bash "$FIXTURE2/scripts/sync-cursor-adapters.sh" 2>&1)
assert_contains "sync reports stale adapter removal" "$sync_output" "removed stale Cursor adapter"
assert_file_not_exists "sync removes orphaned command adapter" "$FIXTURE2/.cursor/commands/research.md"
assert_file_not_exists "sync removes orphaned subagent adapter" "$FIXTURE2/.cursor/agents/tester.md"

sed -i.bak '/^name:/d' "$FIXTURE2/.claude/agents/coder.md"
bash "$FIXTURE2/scripts/sync-cursor-adapters.sh" >/dev/null 2>&1
assert_exit_code "sync fails on unparseable source" 1 "$?"
assert_file_exists "sync keeps adapter of unparseable source" "$FIXTURE2/.cursor/agents/coder.md"

begin_test "Cursor sync guards hand-written files by directory"

FIXTURE3=$(mktemp -d "${TMPDIR:-/tmp}/heph-cursor-XXXXXX")
trap 'rm -rf "$FIXTURE" "$FIXTURE_RULE" "$FIXTURE2" "$FIXTURE3"' EXIT

copy_fixture "$FIXTURE3"

# .cursor/rules/ is shared with the project's own rules — left alone, no error.
printf -- '---\nalwaysApply: true\n---\nProject rule.\n' > "$FIXTURE3/.cursor/rules/mine.mdc"
# A rule generated by some OTHER tool carries a generic "do not edit directly"
# banner. Deleting it would be silent and unrecoverable, so the ownership marker
# must name one of OUR canonical source dirs, not just any auto-gen banner.
printf -- '---\nalwaysApply: true\n---\n<!-- AUTOGENERATED by my-rulegen; do not edit directly -->\nAPI key policy.\n' \
  > "$FIXTURE3/.cursor/rules/other-tool.mdc"
# .cursor/commands/ is generator-owned — a stray file is reported, never deleted.
printf -- 'Do things.\n' > "$FIXTURE3/.cursor/commands/hand-rolled.md"

if foreign_output=$(bash "$FIXTURE3/scripts/sync-cursor-adapters.sh" 2>&1); then
  fail "sync should exit non-zero on non-generated command file" "exited 0, output: $foreign_output"
else
  assert_contains "sync flags non-generated command" "$foreign_output" "non-generated file"
fi
assert_file_exists "non-generated command preserved" "$FIXTURE3/.cursor/commands/hand-rolled.md"
assert_file_exists "project's own Cursor rule preserved" "$FIXTURE3/.cursor/rules/mine.mdc"
assert_file_exists "another tool's generated rule preserved" "$FIXTURE3/.cursor/rules/other-tool.mdc"
assert_not_contains "project's own rule is not flagged" "$foreign_output" "mine.mdc"

# --check must report the stray too, not only sync mode.
if check_foreign=$(bash "$FIXTURE3/scripts/sync-cursor-adapters.sh" --check 2>&1); then
  fail "--check should exit non-zero on non-generated command file" "exited 0"
else
  assert_contains "--check flags non-generated command" "$check_foreign" "hand-rolled.md"
fi

# A copy of one of OUR adapters under a new name carries the original's marker —
# the natural way to customize a subagent. Identity-scoped ownership means it is
# the project's file, so it is reported, never deleted.
rm "$FIXTURE3/.cursor/commands/hand-rolled.md"
cp "$FIXTURE3/.cursor/rules/hephaestus.mdc" "$FIXTURE3/.cursor/rules/hephaestus-old.mdc"
cp "$FIXTURE3/.cursor/agents/reviewer.md" "$FIXTURE3/.cursor/agents/reviewer-strict.md"
copy_output=$(bash "$FIXTURE3/scripts/sync-cursor-adapters.sh" 2>&1)
assert_file_exists "renamed copy of our rule preserved"     "$FIXTURE3/.cursor/rules/hephaestus-old.mdc"
assert_file_exists "renamed copy of our subagent preserved" "$FIXTURE3/.cursor/agents/reviewer-strict.md"
assert_file_exists "other tool's rule still preserved"      "$FIXTURE3/.cursor/rules/other-tool.mdc"
assert_contains    "renamed subagent copy is reported"      "$copy_output" "reviewer-strict.md"

# A genuinely stale adapter names its OWN, now-missing source — still reclaimed.
rm -f "$FIXTURE3/.cursor/agents/reviewer-strict.md"
sed 's|generated from .claude/agents/reviewer.md|generated from .claude/agents/retired.md|' \
  "$FIXTURE3/.cursor/agents/reviewer.md" > "$FIXTURE3/.cursor/agents/retired.md"
reclaim_output=$(bash "$FIXTURE3/scripts/sync-cursor-adapters.sh" 2>&1)
assert_contains        "sync reclaims a genuinely stale adapter" "$reclaim_output" "removed stale Cursor adapter"
assert_file_not_exists "stale adapter removed"                   "$FIXTURE3/.cursor/agents/retired.md"

begin_test "Cursor commands carry no frontmatter and keep \$ARGUMENTS"

start="$HEPHAESTUS_ROOT/.cursor/commands/start-issue.md"
ship="$HEPHAESTUS_ROOT/.cursor/commands/ship.md"
orient="$HEPHAESTUS_ROOT/.cursor/commands/orient.md"

# Cursor injects .cursor/commands/*.md verbatim — YAML frontmatter would reach
# the model as literal text, so no adapter may carry any.
frontmattered=""
for cmd_file in "$HEPHAESTUS_ROOT"/.cursor/commands/*.md; do
  [ "$(head -1 "$cmd_file")" = "---" ] && frontmattered="$frontmattered $(basename "$cmd_file")"
done
assert_eq "no command opens with frontmatter" "" "$frontmattered"
# Cursor substitutes $ARGUMENTS and $1..$n, so the placeholder must survive.
assert_contains "start-issue keeps \$ARGUMENTS" "$(cat "$start")" '$ARGUMENTS'
# The hover preview is the first non-blank line — it must be the description.
assert_contains "first line is the workflow description" "$(head -1 "$start")" "Start working on issue"
assert_contains "start-issue declares requires" "$(cat "$start")" "<!-- requires: coder, explorer -->"
assert_contains "start-issue names its source" "$(cat "$start")" "generated from .ai/workflows/start-issue.md"
assert_contains "orient is generated too" "$(cat "$orient")" "generated from .ai/workflows/orient.md"

