#!/usr/bin/env bash
# test_cursor_adapters.sh — Verify Cursor adapters stay in sync with canonical sources.

set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/helpers.sh"

begin_test "Cursor adapters match workflows and Claude agents"

if output=$(bash "$HEPHAESTUS_ROOT/scripts/sync-cursor-adapters.sh" --check 2>&1); then
  pass "sync-cursor-adapters.sh --check exits 0"
else
  fail "sync-cursor-adapters.sh --check exits non-zero" "$output"
fi

copy_fixture() {
  local dest=$1
  cp -R "$HEPHAESTUS_ROOT/.ai" "$dest/.ai"
  cp -R "$HEPHAESTUS_ROOT/.claude" "$dest/.claude"
  cp -R "$HEPHAESTUS_ROOT/.cursor" "$dest/.cursor"
  mkdir -p "$dest/scripts"
  cp "$HEPHAESTUS_ROOT/scripts/sync-cursor-adapters.sh" "$dest/scripts/sync-cursor-adapters.sh"
  cp "$HEPHAESTUS_ROOT/scripts/models.sh" "$dest/scripts/models.sh"
}

begin_test "Cursor adapter check detects command drift"

FIXTURE=$(mktemp -d "${TMPDIR:-/tmp}/heph-cursor-XXXXXX")
trap 'rm -rf "$FIXTURE"' EXIT

copy_fixture "$FIXTURE"

sed -i.bak 's/Run the full autonomous pipeline/Run the drifted autonomous pipeline/' \
  "$FIXTURE/.cursor/commands/autopilot.md"
rm -f "$FIXTURE/.cursor/commands/autopilot.md.bak"

if drift_output=$(bash "$FIXTURE/scripts/sync-cursor-adapters.sh" --check 2>&1); then
  fail "Cursor adapter check should detect command drift" "exited 0, output: $drift_output"
else
  if echo "$drift_output" | grep -q "Cursor adapter drift for /autopilot"; then
    pass "Cursor adapter check reports /autopilot drift"
  else
    fail "Cursor adapter check failed without naming /autopilot" "$drift_output"
  fi
fi

begin_test "Cursor adapter check detects rule drift"

FIXTURE_RULE=$(mktemp -d "${TMPDIR:-/tmp}/heph-cursor-XXXXXX")
trap 'rm -rf "$FIXTURE" "$FIXTURE_RULE"' EXIT

copy_fixture "$FIXTURE_RULE"

sed -i.bak 's#| /ship | /critique |#| /ship | /nowhere |#' "$FIXTURE_RULE/.cursor/rules/hephaestus.mdc"
rm -f "$FIXTURE_RULE/.cursor/rules/hephaestus.mdc.bak"

if rule_output=$(bash "$FIXTURE_RULE/scripts/sync-cursor-adapters.sh" --check 2>&1); then
  fail "Cursor adapter check should detect rule drift" "exited 0, output: $rule_output"
